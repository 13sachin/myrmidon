"""Append-only provenance ledger: the trail every study leaves behind.

One JSONL file per workspace. Every tool call becomes a ProvenanceEvent with
the exact validated params, the exact argv (when a binary ran), engine
versions, and hashed input/output artifacts. ``replay_script()`` renders the
command sequence that reproduces the study.
"""

from __future__ import annotations

import json
import uuid
from collections.abc import Iterator
from contextvars import ContextVar
from datetime import UTC, datetime
from pathlib import Path

from pydantic import BaseModel, Field

from myrmidon.core.artifacts import ArtifactRef

LEDGER_FILENAME = "myrmidon.ledger.jsonl"

#: (plan_id, plan_step) of the call the registry is running: the plan on disk when it was
#: made and the step it carried out. Set by the registry, read by the ledger event and by
#: the job store, so a submission carries the same tags as the call that made it.
CALL_PLAN: ContextVar[tuple[str, str]] = ContextVar("CALL_PLAN", default=("", ""))
#: the event id the running call will be recorded under, minted when the call starts, so a
#: job submitted during the call can name the event that submitted it
CALL_EVENT: ContextVar[str] = ContextVar("CALL_EVENT", default="")


def new_event_id() -> str:
    return "ev-" + uuid.uuid4().hex[:12]


class ProvenanceEvent(BaseModel):
    event_id: str = Field(default_factory=new_event_id)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))
    tool: str
    params: dict = Field(default_factory=dict)
    command: list[str] | None = None
    engine_versions: dict[str, str] = Field(default_factory=dict)
    myrmidon_version: str = ""
    inputs: list[ArtifactRef] = Field(default_factory=list)
    outputs: list[ArtifactRef] = Field(default_factory=list)
    warnings_acknowledged: list[str] = Field(default_factory=list)
    ok: bool = True
    duration_s: float | None = None
    exit_code: int | None = None
    kind: str = "call"  # "call" | "observe" | "gate_refused"
    # ids of the findings the call surfaced (gate, advisory, diagnosis): the durable
    # knowledge in play, by the name the code gives it
    knowledge_refs: list[str] = Field(default_factory=list)
    # the approval event (a plan_approve, core/approvals.py) an acknowledgement in this call
    # relied on. Empty with acknowledged warnings means the agent accepted them itself.
    approval: str = ""
    # Hash of the tool's params model JSON schema at the time of the call, so a
    # changed model cannot silently break the replay of an old ledger.
    params_schema: str = ""
    # the plan this call was made under (plan.yaml's plan_id when it ran) and the step of it
    # the call carried out, when an approved plan bound it. A plan's steps are satisfied by
    # its own calls only: a study holds many questions, and a call made for one says nothing
    # about another's
    plan_id: str = ""
    plan_step: str = ""


class ProvenanceLedger:
    def __init__(self, path: Path):
        self.path = path

    def append(self, event: ProvenanceEvent) -> str:
        with self.path.open("a") as fh:
            fh.write(json.dumps(event.model_dump(mode="json"), sort_keys=True) + "\n")
        return event.event_id

    def events(self) -> Iterator[ProvenanceEvent]:
        if not self.path.exists():
            return
        with self.path.open() as fh:
            for line in fh:
                line = line.strip()
                if line:
                    yield ProvenanceEvent.model_validate_json(line)

    def get(self, event_id: str) -> ProvenanceEvent | None:
        for ev in self.events():
            if ev.event_id == event_id:
                return ev
        return None

    def last_output(self, path: str) -> ArtifactRef | None:
        """The most recent record of ``path`` (workspace-relative) as a call's output: what
        the file hashed to when the harness produced it. None when no call produced it."""
        found = None
        for ev in self.events():
            for art in ev.outputs:
                if art.path == path:
                    found = art
        return found

    def replay_script(self) -> str:
        """Shell script of the exact commands that produced this study.

        Paths under the workspace root are rendered relative, so the script
        reproduces the study from any copy of the workspace.
        """
        root = str(self.path.parent.resolve())
        lines = [
            "#!/bin/sh",
            "# Generated by myrmidon from the provenance ledger.",
            "# Run from the workspace root to reproduce the study.",
            "set -eux",
            "",
        ]
        for ev in self.events():
            if ev.command:
                stamp = ev.timestamp.isoformat(timespec="seconds")
                args = [a.replace(root + "/", "") for a in ev.command]
                lines.append(f"# {ev.event_id} · {ev.tool} · {stamp}")
                lines.append(" ".join(shquote(a) for a in args))
                lines.append("")
        return "\n".join(lines)


def shquote(arg: str) -> str:
    if arg and all(c.isalnum() or c in "@%+=:,./-_" for c in arg):
        return arg
    return "'" + arg.replace("'", "'\\''") + "'"
