"""CPMD input parsing/patching and the mimic_prepare review tool.

CPMD inputs are &SECTION ... &END blocks with keyword lines whose values sit
on the following line(s). MiMiCPy's prepqm generates the initial cpmd.inp;
mimic_prepare turns it into a reviewed run input. The QM region's charge is the one prepqm
summed from the selected atoms' topology charges, unless that sum was not an integer; its
multiplicity is the one its electron count decides (an even count with no open-shell metal
is a singlet). Either is derived and said when it can be, asked for when it cannot, and
taken as given when the researcher stated it."""

from __future__ import annotations

import json

from pydantic import BaseModel, Field

from myrmidon.core.artifacts import ArtifactRef
from myrmidon.core.contracts import Contract, Produces
from myrmidon.core.observation import Observation, ToolError
from myrmidon.core.tool import ToolContext, precheck, tool
from myrmidon.core.validation import Finding
from myrmidon.engines.inputs import resolve_in_ws
from myrmidon.engines.mimic.cpmd_input import (
    DistanceRestraint,
    add_distance_restraints,
    apply_method,
    drop_keyword,
    get_keyword,
    has_keyword,
    parse_cpmd,
    render_cpmd,
    set_keyword,
)
from myrmidon.engines.mimic.system import electron_count, spin_state
from myrmidon.knowledge.sensors import evaluate


class MimicPrepareParams(BaseModel):
    cpmd_input: str = Field(description="cpmd.inp generated by qm_region")
    total_charge: int | None = Field(
        default=None, description="net charge of the QM region; unset, the selected atoms' "
        "topology charges decide it when they sum to an integer")
    multiplicity: int | None = Field(
        default=None, ge=1, description="spin multiplicity; unset, the QM electrons decide "
        "it when their count is even and no open-shell metal is present")
    maxsteps: int | None = Field(
        default=None,
        description="&CPMD MAXSTEP — MD steps under MOLECULAR DYNAMICS, but SCF "
                    "iterations under WAVEFUNCTION OPTIMIZATION (every single point). "
                    "Leave unset for a single point: CPMD's own limit is the right one, "
                    "and a small value returns an unconverged wavefunction with exit 0")
    timestep_au: float | None = Field(default=None, description="&CPMD TIMESTEP (a.u.)")
    fm_pace: int | None = Field(
        default=None, ge=1,
        description="&CPMD FORCE_MATCHING pace — write FM reference data every N MD steps",
    )
    distance_restraints: list[DistanceRestraint] = Field(
        default_factory=list,
        description="harmonic distance restraints (CPMD atom numbers, &ATOMS order). "
        "mimic_run warns on them (CPMD_RESTRAINTS_UNDER_MIMIC): CPMD builds without PLUMED "
        "hooks segfault applying them in a coupled run",
    )
    method: str | None = Field(
        default=None,
        description="a stage's method: the CPMD input inputset_apply rendered from the "
        "stage's input set (annealing, NVE test, heating, production). Its &CPMD, &DFT and "
        "method keywords are used; the system — &ATOMS, &MIMIC OVERLAPS/PATHS/BOX, &SYSTEM "
        "CELL — stays the one cpmd_input holds. One QM selection, every stage.",
    )
    output: str = Field(
        default="cpmd_run.inp",
        description="a bare filename is written beside the input it is made from; a "
        "path with a directory is workspace-relative, as every other tool's output is",
    )


def _output_path(ctx: ToolContext, src, output: str):
    """Where the reviewed input is written.

    A bare filename lands beside the input it was made from. A path with a directory in
    it is workspace-relative, like every other tool's ``output``; resolved against the
    input's directory instead, ``02_heating/cpmd_run.inp`` would silently become
    ``02_heating/02_heating/...``. Returns None for a path that escapes.
    """
    from pathlib import Path

    candidate = Path(output)
    if candidate.is_absolute() or len(candidate.parts) > 1:
        root = ctx.workspace.root.resolve()
        out = (root / candidate).resolve() if not candidate.is_absolute() else candidate
        return out if str(out).startswith(str(root) + "/") else None
    return src.parent / output




def _origin(ctx: ToolContext, given: str):
    """(the successful calls that wrote these bytes, whether they are the QM selection's,
    whether the selection behind the input — followed back through each writer's own
    `cpmd_input` — marks boundary atoms) — the input as the ledger knows it."""
    from myrmidon.core.artifacts import sha256_file
    from myrmidon.core.lineage import lineage

    lin = lineage(ctx.workspace)
    writers = lin.writers.get(sha256_file(resolve_in_ws(ctx, given)), [])
    bound, frontier, seen = False, list(writers), set()
    while frontier:
        ev = frontier.pop()
        if ev.event_id in seen:
            continue
        seen.add(ev.event_id)
        bound = bound or any("add-bound" in str(sel)
                             for sel in ev.params.get("selections") or [])
        frontier += [w for inp in ev.inputs if inp.role == "cpmd_input"
                     for w in lin.writers.get(inp.sha256, [])]
    return (writers, bool(writers) and all(ev.tool == "qm_region" for ev in writers),
            bound)


def _derived_charge(writers, selected: bool, sections: dict) -> tuple[int | None, str]:
    """(the QM charge the input declares, whose it is) — or (None, why it is open). Derived
    only from prepqm's integer sum of the selected atoms' topology charges (an input the
    QM selection wrote, none of whose writers rounded it), or from an input no recorded call
    wrote (the researcher's own); an input anything else wrote is asked about."""
    declared = get_keyword(sections.get("SYSTEM", []), "CHARGE")
    if declared is None or not declared.strip():
        return None, "the input declares no charge"
    try:
        value = int(round(float(declared)))
    except ValueError:
        return None, f"the input declares the charge {declared.strip()!r}"
    if any("QM_CHARGE_ROUNDED" in ev.knowledge_refs for ev in writers):
        return None, ("the selected atoms' topology charges sum to a non-integer, which "
                      f"prepqm rounded to {declared.strip()}")
    if not writers:
        return value, f"charge {value}: declared by the input you supplied"
    if selected:
        return value, f"charge {value}: the selected atoms' topology charges (prepqm)"
    return None, ("the input was written by " + ", ".join(sorted({ev.tool for ev in writers}))
                  + ", not by the QM selection, so its charge is not the topology's sum")


def prepare_gate(ctx: ToolContext, params: MimicPrepareParams):
    """Where did the QM method settings come from? The cpmd.inp reaching this tool was
    built by prepqm from a template, and the template is what carries the functional,
    the cutoff and the coupling — so the question is about the template."""
    from myrmidon.core.sourcing import parameter_source, sourced_finding, unsourced_finding

    warnings: list[Finding] = []
    checked = ["parameter_source"]
    if ctx.workspace is not None:
        sources = [parameter_source(ctx.workspace, params.cpmd_input)]
        for finding in (unsourced_finding(sources), sourced_finding(sources)):
            if finding is not None:
                warnings.append(finding)
        from myrmidon.engines.file_origin import edit_findings

        warnings += edit_findings(ctx, params.cpmd_input)
    return warnings, checked


@tool(
    "mimic_prepare",
    description="Turn the generated cpmd.inp into a MiMiC run input with the charge and "
                "multiplicity written into &SYSTEM: given, or derived from the topology charges "
                "and electron count and said; `needs_input` when the system leaves them open.",
    contract=Contract(consumes={"cpmd_input": "cpmd_input"},
                      produces=(Produces("cpmd_input"),)),
    tags={"mimic", "qmmm"},
    requires={"mimicpy"},
)
def mimic_prepare(ctx: ToolContext, params: MimicPrepareParams) -> Observation:
    precheck(ctx, prepare_gate(ctx, params)[0])
    src = resolve_in_ws(ctx, params.cpmd_input)
    sections = parse_cpmd(src.read_text())
    if params.method:
        method = parse_cpmd(resolve_in_ws(ctx, params.method).read_text())
        if "CPMD" not in method:
            return Observation(
                ok=False,
                summary=f"{params.method} has no &CPMD section, so it states no method",
                sections=sorted(method),
            )
        sections = apply_method(sections, method)
    if "MIMIC" not in sections:
        return Observation(
            ok=False,
            summary=f"{params.cpmd_input} has no &MIMIC section — is this really a "
            "MiMiCPy-generated input?",
            sections=sorted(sections),
        )
    facts, questions, needs = [], [], []
    charge, multiplicity = params.total_charge, params.multiplicity
    writers, selected, bound = _origin(ctx, params.cpmd_input)
    if charge is None:
        charge, why = _derived_charge(writers, selected, sections)
        if charge is None:
            questions.append(f"What is the QM region's net charge? ({why})")
            needs.append("total_charge")
        else:
            facts.append(why)
    else:
        facts.append(f"charge {charge}: given by the call")
    if multiplicity is None and charge is not None:
        multiplicity, why = (None, "the region has boundary atoms, whose pseudopotentials' "
                             "valence decides the electron count") if bound \
            else spin_state(sections, charge)
        if multiplicity is None:
            questions.append(f"What is the QM region's spin multiplicity? ({why})")
            needs.append("multiplicity")
        else:
            facts.append(why)
    elif multiplicity is not None:
        facts.append(f"multiplicity {multiplicity}: given by the call")
    if charge is None or multiplicity is None:
        return Observation(
            ok=False, status="needs_input", questions=questions, facts=facts, needs=needs,
            summary="the QM region's " + " and ".join(
                n for n, v in (("charge", charge), ("multiplicity", multiplicity))
                if v is None) + " are the researcher's: " + " ".join(questions),
            error=ToolError(code="NEEDS_INPUT", message=" ".join(questions),
                            hint="ask the researcher; the answer is a decision in the "
                            "mandate, and the value goes to this call"))
    electrons = None if bound else electron_count(sections, charge)
    findings = evaluate("qm_region", {
        "electrons": electrons, "multiplicity": multiplicity,
        "spin_parity_matches": None if electrons is None
        else electrons % 2 == (multiplicity - 1) % 2})
    system = sections.setdefault("SYSTEM", [])
    sections["SYSTEM"] = set_keyword(system, "CHARGE", str(charge))
    cpmd_sec = sections.setdefault("CPMD", [])
    # CPMD accepts MULTIPLICITY only in a spin-polarized (LSD) run; for a
    # closed-shell singlet the keyword must be absent (CPMD aborts in sysin
    # otherwise, CPMD 4.3). The value always goes to
    # the sidecar so the gate can verify it was set explicitly.
    if multiplicity > 1:
        sections["SYSTEM"] = set_keyword(
            sections["SYSTEM"], "MULTIPLICITY", str(multiplicity)
        )
        if not has_keyword(cpmd_sec, "LSD"):
            cpmd_sec = ["LSD", *cpmd_sec]
            sections["CPMD"] = cpmd_sec
        spin_note = f"multiplicity {multiplicity} (LSD)"
    else:
        sections["SYSTEM"] = drop_keyword(sections["SYSTEM"], "MULTIPLICITY")
        spin_note = "multiplicity 1 (closed shell: no MULTIPLICITY keyword, as CPMD requires)"
    if params.maxsteps is not None:
        sections["CPMD"] = set_keyword(cpmd_sec, "MAXSTEP", str(params.maxsteps))
    if params.timestep_au is not None:
        sections["CPMD"] = set_keyword(
            sections["CPMD"], "TIMESTEP", str(params.timestep_au)
        )
    if params.fm_pace is not None:
        sections["CPMD"] = set_keyword(
            sections["CPMD"], "FORCE_MATCHING", str(params.fm_pace)
        )
    try:
        sections = add_distance_restraints(sections, params.distance_restraints)
    except ValueError as exc:
        return Observation(ok=False, summary=str(exc), sections=sorted(sections))

    out = _output_path(ctx, src, params.output)
    if out is None:
        return Observation(
            ok=False,
            summary=f"output '{params.output}' escapes the workspace",
            sections=sorted(sections),
        )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_cpmd(sections))
    sidecar = out.with_name(out.name + ".myrmidon.json")
    sidecar.write_text(
        json.dumps(
            {
                "charge": charge,
                "multiplicity": multiplicity,
                "derived": facts,
                "source_input": src.name,
                "method": params.method,
            },
            indent=1,
        )
    )

    paths_value = get_keyword(sections.get("MIMIC", []), "PATHS")
    functional = None
    for line in sections.get("DFT", []):
        if line.strip().upper().startswith("FUNCTIONAL"):
            parts = line.split()
            functional = parts[-1] if len(parts) > 1 else None
    maxstep_val = get_keyword(sections.get("CPMD", []), "MAXSTEP")
    timestep_val = get_keyword(sections.get("CPMD", []), "TIMESTEP")
    return Observation(
        ok=True,
        summary=f"MiMiC run input written: charge {charge}, {spin_note}"
        + (f", {maxstep_val} steps" if maxstep_val else "")
        + (f", FM pace {params.fm_pace}" if params.fm_pace else "")
        + (
            f", {len(params.distance_restraints)} distance restraint(s)"
            if params.distance_restraints
            else ""
        )
        + f" -> {ctx.workspace.relpath(out)}",
        artifacts=[
            ArtifactRef.from_path(out, "cpmd_input", root=ctx.workspace.root),
            ArtifactRef.from_path(sidecar, "run_metadata", root=ctx.workspace.root),
        ],
        facts=facts,
        findings=findings,
        charge=charge,
        multiplicity=multiplicity,
        maxsteps=int(maxstep_val) if maxstep_val and maxstep_val.isdigit() else None,
        timestep_au=float(timestep_val) if timestep_val else None,
        functional=functional,
        paths=int(paths_value) if paths_value and paths_value.isdigit() else None,
        sections=sorted(sections),
    )
